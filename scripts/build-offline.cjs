// Regenerate after changing any shipped asset; --check is used by tests.
const fs = require("node:fs");
const crypto = require("node:crypto");
const hash = (data) => crypto.createHash("sha256").update(data).digest("hex");
const html = fs.readFileSync("index.html", "utf8");
const urls = new Set(["index.html", "manifest.webmanifest"]);
for (const [, url] of html.matchAll(/(?:src|href)="([^"#]+)"/g)) {
  if (!/^https?:/.test(url)) urls.add(url);
}
for (const file of fs.readdirSync("assets/images")) urls.add("assets/images/" + file);
const assets = [...urls]
  .sort()
  .map((url) => ({ url, sha: hash(fs.readFileSync(url.split("?")[0])) }));
const revision = hash(JSON.stringify(assets) + fs.readFileSync("service-worker.js", "utf8")).slice(
  0,
  20,
);
const output =
  "// Generated by scripts/build-offline.cjs. Do not edit.\nvar OFFLINE_BUILD = " +
  JSON.stringify({ revision, assets }, null, 2) +
  ";\n";
if (process.argv.includes("--check")) {
  if (fs.readFileSync("offline-assets.js", "utf8") !== output)
    throw Error("Offline assets are stale: npm run build:offline");
} else fs.writeFileSync("offline-assets.js", output);
console.log("Offline assets: " + assets.length + "; revision " + revision);
